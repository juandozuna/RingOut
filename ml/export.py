"""Write trained TCN weights to Sources/RingOutEngine/NeuralWeights.inc.

Usage: python export.py <checkpoint.pt | --random> [--out PATH]

The header also embeds a parity vector: a deterministic test signal (see
`parity_input`, mirrored in NeuralIsolator.cpp) and the PyTorch output for it,
so the engine can verify its port of the network at launch and in tests.
"""
from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path

import torch

from model import TCN, StreamingTCN, RECEPTIVE_FIELD

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "Sources/RingOutEngine/NeuralWeights.inc"
PARITY_N = 4096


def parity_input(n: int = PARITY_N) -> torch.Tensor:
    """Two sines, a growing 2.5 kHz 'ring' and LCG noise. Same formula in C++."""
    out = []
    state = 12345
    for i in range(n):
        state = (1103515245 * state + 12345) & 0x7FFFFFFF
        noise = (state / 2147483647.0) * 2.0 - 1.0
        t = i / 48000.0
        ring = min(1.0, i / n * 2.0) * 0.4 * math.sin(2 * math.pi * 2500.0 * t)
        v = 0.2 * math.sin(2 * math.pi * 220.0 * t) + 0.1 * math.sin(2 * math.pi * 1210.0 * t) + ring + 0.05 * noise
        out.append(v)
    return torch.tensor(out, dtype=torch.float32)


def fmt(values) -> str:
    vals = [f"{float(v):.9g}f" for v in values]
    lines = [", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
    return "{\n    " + ",\n    ".join(lines) + "}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt", nargs="?")
    ap.add_argument("--random", action="store_true", help="export a random model (for porting work)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    model = TCN()
    label = "random-init"
    if args.random:
        torch.manual_seed(7)
        torch.nn.init.normal_(model.out.weight, std=0.2)
        torch.nn.init.normal_(model.out.bias, std=0.01)
    else:
        ck = torch.load(args.ckpt, map_location="cpu")
        model.load_state_dict(ck["model"])
        label = ck.get("label", Path(args.ckpt).stem)
    model.eval()

    C, L = model.C, len(model.dilations)
    x = parity_input()
    y = StreamingTCN(model).process(x.unsqueeze(0))[0]

    blobs: dict[str, torch.Tensor] = {
        "kInW": model.inp.weight.view(C),
        "kInB": model.inp.bias,
        "kDilW0": torch.stack([m.weight[:, :, 0] for m in model.dil]),  # [L][2C][C], multiplies h[t-d]
        "kDilW1": torch.stack([m.weight[:, :, 1] for m in model.dil]),  # [L][2C][C], multiplies h[t]
        "kDilB": torch.stack([m.bias for m in model.dil]),              # [L][2C]
        "kResW": torch.stack([m.weight[:, :, 0] for m in model.res]),   # [L][C][C]
        "kResB": torch.stack([m.bias for m in model.res]),              # [L][C]
        "kSkipW": torch.stack([m.weight[:, :, 0] for m in model.skip]), # [L][C][C]
        "kSkipB": torch.stack([m.bias for m in model.skip]),            # [L][C]
        "kHeadW": model.head.weight[:, :, 0],                           # [C][C]
        "kHeadB": model.head.bias,                                      # [C]
        "kOutW": model.out.weight.view(C),                              # [C]
        "kOutB": model.out.bias.view(1),                                # [1]
    }
    h = hashlib.sha256()
    for t in blobs.values():
        h.update(t.detach().contiguous().numpy().tobytes())
    digest = h.hexdigest()[:16]

    lines = [
        "// GENERATED by ml/export.py. Do not edit.",
        f"// Model: {label}, sha256/16 {digest}",
        "// Matrices are row-major [out][in]; see ml/model.py for the forward pass.",
        "#pragma once",
        "",
        "namespace ro::nnw {",
        "",
        f"constexpr int kChannels = {C};",
        f"constexpr int kLayers = {L};",
        f"constexpr int kReceptiveField = {RECEPTIVE_FIELD};",
        "constexpr int kDilations[kLayers] = {" + ", ".join(map(str, model.dilations)) + "};",
        f'constexpr const char* kModelId = "{label}-{digest}";',
        "",
    ]
    for name, t in blobs.items():
        flat = t.detach().reshape(-1).tolist()
        lines.append(f"alignas(16) constexpr float {name}[{len(flat)}] = {fmt(flat)};")
        lines.append("")
    lines.append(f"constexpr int kParityLength = {PARITY_N};")
    lines.append(f"alignas(16) constexpr float kParityOutput[kParityLength] = {fmt(y.tolist())};")
    lines.append("")
    lines.append("}  // namespace ro::nnw")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} ({label}-{digest}); parity rms in {x.pow(2).mean().sqrt():.3f} out {y.pow(2).mean().sqrt():.3f}")


if __name__ == "__main__":
    main()
